#!/usr/bin/env python3
"""Embeds joystick/web/telemetry.html into joystick/src/phone_page.h (C++ raw string).

Run after editing the page:  py tools/gen_phone_page.py
tools/test_phone_page.py fails if the header is out of date.
"""

from __future__ import annotations

import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "joystick", "web", "telemetry.html")
DST = os.path.join(ROOT, "joystick", "src", "phone_page.h")

DELIM = "STAMPFLYPAGE"


def read_page() -> str:
    with open(SRC, "r", encoding="utf-8", newline="") as f:
        return f.read().replace("\r\n", "\n")


def render_header(page: str) -> str:
    assert ")" + DELIM + '"' not in page
    return (
        "// SPDX-License-Identifier: MIT\n"
        "//\n"
        "// [POSHOLD] GENERATED by tools/gen_phone_page.py from joystick/web/telemetry.html. Do not edit.\n"
        "\n"
        "#ifndef PHONE_PAGE_H\n"
        "#define PHONE_PAGE_H\n"
        "\n"
        "static const char kPhonePage[] = R\"" + DELIM + "(" + page + ")" + DELIM + "\";\n"
        "\n"
        "#endif\n"
    )


def main() -> int:
    with open(DST, "w", encoding="utf-8", newline="") as f:
        f.write(render_header(read_page()))
    print("Wrote %s" % DST)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
